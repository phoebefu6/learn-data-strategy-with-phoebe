def main() -> None:
    rows = [dict(zip(FIELDS, r)) for r in ROWS]
    ids = [r["id"] for r in rows]
    assert len(set(ids)) == len(ids) == 24
    for r in rows:
        assert all(d in ids for d in r["deps"]), r["id"]
        assert (r["ready"] < 40) == bool(r["gap"]), r["id"]
    payload = {
        "case": "Keelson Mutual (constructed)",
        "note": "Constructed portfolio for teaching. No row is a measurement of any real insurer.",
        "units": {"value": "band 1-10", "effort": "team-months", "cost": "thousands, constructed",
                  "ready": "data readiness 0-100", "reg": "regulatory risk 1-3"},
        "budget": 1100, "capacity": 24, "gate": 40,
        "rows": rows,
    }
    out = Path(__file__).resolve().parent.parent / "assets" / "bets-data.js"
    out.write_text("/* Keelson Mutual use-case portfolio, CONSTRUCTED for teaching. Generated by "
                   "materials/build-bets-data.py with json.dumps. */\nwindow.BETS_DATA = "
                   + json.dumps(payload, indent=1) + ";\n", encoding="utf-8")
    print("wrote", out, out.stat().st_size, "bytes")


if __name__ == "__main__":
    main()
