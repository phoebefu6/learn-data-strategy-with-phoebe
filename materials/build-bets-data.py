#!/usr/bin/env python3
"""Write assets/bets-data.js: Keelson Mutual's CONSTRUCTED use-case portfolio.

Keelson Mutual is a constructed mid-size insurer. None of these rows is a measurement of any real
company. Value is a 1-10 band agreed in a constructed scoring workshop, effort is team-months,
cost is in thousands (constructed), readiness is a 0-100 data-readiness score, reg is regulatory
risk 1 (low) to 3 (high), deps are use cases that must be delivered first, gap names the missing
data for any row with readiness under the gate.

Serialised with json.dumps (never string interpolation). Run from the repo root:
    python3 materials/build-bets-data.py
"""
